#!/usr/bin/env node

import { promises as fs } from "node:fs"
import path from "node:path"
import process from "node:process"
import { fileURLToPath } from "node:url"
import { parse as parseJsonc } from "jsonc-parser"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const store = path.join(root, "node_modules", ".bun")
const output = path.join(root, "THIRD_PARTY_DEPENDENCIES.md")
const lockfile = path.join(root, "bun.lock")

const licenseOverrides = new Map([
  ["@openauthjs/openauth@0.0.0-20250322224806", "MIT"],
  ["poe-oauth@0.0.8", "MIT"],
  ["seq-queue@0.0.5", "MIT"],
])

const cleanRepository = (value) => {
  const raw = typeof value === "string" ? value : value?.url
  if (!raw) return ""
  return raw.replace(/^git\+/, "").replace(/^git@github\.com:/, "https://github.com/").replace(/\.git$/, "")
}

const cleanLicense = (pkg, key) => {
  if (typeof pkg.license === "string") return pkg.license
  if (Array.isArray(pkg.licenses)) {
    const values = pkg.licenses.map((item) => (typeof item === "string" ? item : item?.type)).filter(Boolean)
    if (values.length) return values.join(" OR ")
  }
  return licenseOverrides.get(key) ?? "NOASSERTION"
}

const supportsPlatform = (constraint, current) => {
  if (!constraint) return true
  const values = Array.isArray(constraint) ? constraint : [constraint]
  if (values.includes(`!${current}`)) return false
  const included = values.filter((value) => typeof value === "string" && !value.startsWith("!"))
  return included.length === 0 || included.includes(current)
}

const packageDirectories = async () => {
  const result = []
  for (const entry of await fs.readdir(store, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    const modules = path.join(store, entry.name, "node_modules")
    const children = await fs.readdir(modules, { withFileTypes: true }).catch(() => [])
    for (const child of children) {
      if (!child.isDirectory()) continue
      if (!child.name.startsWith("@")) {
        result.push(path.join(modules, child.name))
        continue
      }
      const scope = path.join(modules, child.name)
      for (const scoped of await fs.readdir(scope, { withFileTypes: true }).catch(() => [])) {
        if (scoped.isDirectory()) result.push(path.join(scope, scoped.name))
      }
    }
  }
  return result
}

const records = new Map()
const lock = parseJsonc(await fs.readFile(lockfile, "utf8"))
const lockedPackages = new Set(
  Object.values(lock.packages ?? {})
    .map((item) => (Array.isArray(item) ? item[0] : undefined))
    .filter((item) => typeof item === "string"),
)

for (const directory of await packageDirectories()) {
  const pkg = await fs
    .readFile(path.join(directory, "package.json"), "utf8")
    .then(JSON.parse)
    .catch(() => undefined)
  if (!pkg?.name || !pkg?.version) continue
  if (!supportsPlatform(pkg.os, process.platform) || !supportsPlatform(pkg.cpu, process.arch)) continue

  const key = `${pkg.name}@${pkg.version}`
  if (!lockedPackages.has(key)) continue
  const files = await fs.readdir(directory, { withFileTypes: true }).catch(() => [])
  const notices = files
    .filter((item) => item.isFile() && /^(license|licence|copying|notice|ofl)(\..*)?$/i.test(item.name))
    .map((item) => item.name)
    .sort()

  records.set(key, {
    name: pkg.name,
    version: pkg.version,
    license: cleanLicense(pkg, key),
    repository: cleanRepository(pkg.repository) || pkg.homepage || "",
    notices,
  })
}

const packages = [...records.values()].sort((a, b) =>
  a.name === b.name ? a.version.localeCompare(b.version) : a.name.localeCompare(b.name),
)
const licenseCounts = new Map()
for (const item of packages) licenseCounts.set(item.license, (licenseCounts.get(item.license) ?? 0) + 1)

const cell = (value) => String(value).replaceAll("|", "\\|").replaceAll("\n", " ")
const lines = [
  "# Third-Party Dependency Inventory",
  "",
  "> Generated by `node tools/generate-third-party-inventory.mjs`. Do not edit manually.",
  "",
  `This inventory contains ${packages.length} unique package versions that are selected by \`bun.lock\`, present in the Bun installation, and compatible with \`${process.platform}/${process.arch}\`.`,
  "Package-specific license and notice files remain authoritative.",
  "",
  "## License Summary",
  "",
  "| License declaration | Packages |",
  "| --- | ---: |",
  ...[...licenseCounts].sort(([a], [b]) => a.localeCompare(b)).map(([license, count]) => `| ${cell(license)} | ${count} |`),
  "",
  "## Packages",
  "",
  "| Package | Version | License | Included notice files | Repository |",
  "| --- | --- | --- | --- | --- |",
  ...packages.map((item) => {
    const repository = item.repository ? `<${item.repository}>` : ""
    return `| ${cell(item.name)} | ${cell(item.version)} | ${cell(item.license)} | ${cell(item.notices.join(", "))} | ${repository} |`
  }),
  "",
].join("\n")

if (process.argv.includes("--check")) {
  const current = await fs.readFile(output, "utf8").catch(() => "")
  if (current !== lines) {
    console.error("THIRD_PARTY_DEPENDENCIES.md is missing or stale. Regenerate it with:")
    console.error("  node tools/generate-third-party-inventory.mjs")
    process.exit(1)
  }
  console.log(`Third-party dependency inventory is current (${packages.length} package versions).`)
  process.exit(0)
}

await fs.writeFile(output, lines)
console.log(`Wrote THIRD_PARTY_DEPENDENCIES.md (${packages.length} package versions).`)
